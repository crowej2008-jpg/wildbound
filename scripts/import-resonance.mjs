#!/usr/bin/env node
/* eslint-disable no-undef */
/**
 * R7: import the source's Resonance into packages/content/tuning/resonance.json.
 *
 * Source (modepages-growth_cfg): hero_share_basic_json (2 open slots, 6 more free at crystal evolution, evolution
 * at Lv 340, a 24-hour slot cooldown cleared for 4 Diamonds an hour), hero_share_extraopen_json (the price of
 * each bought slot in Resonation Shards or Diamonds), and the `_server_hero_share_info` research note — the
 * server's own answers from 39 accounts: the slot limits (82, 88 evolved), the price row (open + 1, evolved
 * open − 5), the evolved cap rule (need_pet_num = floor((level − 340) / 8) + 1 Pokémon at 12★) and the cost of
 * the next crystal level at the levels read (XP Candy, Gold = 3 × Candy, Ascension Stones). Levels between the
 * reads are interpolated by the engine (ASSUMPTIONS #71).
 *
 *   WILDBOUND_SOURCE=…/h5-client node scripts/import-resonance.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { dumpFiles, loadTable, repoRoot } from './source/source.mjs';

const basic = loadTable('hero_share_basic_json');
const extra = loadTable('hero_share_extraopen_json');
let reads;
for (const file of dumpFiles()) {
  const dump = JSON.parse(readFileSync(file, 'utf8'));
  if (dump._server_hero_share_info) reads = dump._server_hero_share_info;
}
if (!reads) throw new Error('no _server_hero_share_info note');

const SHARD = 10059;
const DIAMOND = 2;
const slotPrices = Object.values(extra)
  .sort((a, b) => a.open_num - b.open_num)
  .map((r) => ({
    openNum: r.open_num,
    shards: r.cost_item?.find(([id]) => id === SHARD)?.[1] ?? 0,
    gems: r.cost_gold?.find(([id]) => id === DIAMOND)?.[1] ?? 0,
  }));

const upgrade = new Map();
for (const r of reads) {
  if (!r.level_up_items?.length) continue;
  const get = (id) => r.level_up_items.find((x) => x.id === id)?.num ?? 0;
  const row = { level: r.level, candy: get(27), gold: get(1), stones: get(20601) };
  if (row.gold !== row.candy * 3) throw new Error(`gold is not 3 × candy at ${r.level}`);
  upgrade.set(r.level, row);
}
const evolvedMax = Math.max(...reads.filter((r) => r.phase === 1).map((r) => r.max_nums));
const unevolvedMax = Math.max(...reads.filter((r) => r.phase === 0).map((r) => r.max_nums));

const out = {
  _note: 'Generated by scripts/import-resonance.mjs from the source (hero_share_* tables and the server reads). Do not edit.',
  defaultSlots: basic.default_num,
  evolutionSlots: basic.evolution_num,
  evolutionLevel: basic.evolution_lev,
  cooldownHours: basic.cd,
  clearGemsPerHour: basic.clear_cd,
  maxSlots: unevolvedMax,
  maxSlotsEvolved: evolvedMax,
  // need_pet_num = floor((level − capBase) / capPerPokemon) + 1 Pokémon at capStars★ or more.
  capBase: basic.evolution_lev,
  capPerPokemon: 8,
  capStars: 12,
  slotPrices,
  upgradePoints: [...upgrade.values()].sort((a, b) => a.level - b.level).map(({ level, candy, stones }) => ({ level, candy, stones })),
  goldPerCandy: 3,
};
writeFileSync(join(repoRoot, 'packages/content/tuning/resonance.json'), JSON.stringify(out, null, 1) + '\n');
console.log(`resonance: ${slotPrices.length} slot prices, ${out.upgradePoints.length} upgrade points, slots ${out.maxSlots} / ${out.maxSlotsEvolved}`);

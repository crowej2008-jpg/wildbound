/* eslint-disable no-undef */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { describeTable, loadCatalog, repoRoot, sourceRoot } from './source.mjs';

/**
 * Writes docs/SOURCE-TABLES.md: every table in the source game's config dumps, which dump holds it,
 * its row count and the first row's field names. Committed so agents without the gitignored
 * reference/ folder (cloud sessions, CI) can still see what the source contains. Re-run after the
 * dumps change:
 *
 *   node scripts/source/index-tables.mjs
 */

const tables = loadCatalog(sourceRoot);
const byFile = new Map();
for (const [name, entry] of tables) {
  if (!byFile.has(entry.file)) byFile.set(entry.file, []);
  byFile.get(entry.file).push([name, describeTable(entry.data)]);
}

const lines = [
  '# Source tables',
  '',
  'Generated by `node scripts/source/index-tables.mjs` from the source game\'s config dumps',
  '(`reference/game-rebuild/data/h5-client/`, gitignored — on the owner\'s PC). Load any table with',
  '`loadTable(name)` / `tableRows(name)` from `scripts/source/source.mjs`. When a table is in more',
  'than one dump the latest-dated dump wins. Human notes on each system: `reference/game-rebuild/kb/`.',
  '',
  `${tables.size} tables in ${byFile.size} dumps.`,
  '',
];
for (const file of [...byFile.keys()].sort()) {
  lines.push(`## ${file}`, '', '| Table | Rows | Fields (first row) |', '|---|---|---|');
  for (const [name, info] of byFile.get(file).sort((a, b) => a[0].localeCompare(b[0]))) {
    const fields = info.fields.slice(0, 12).join(', ') + (info.fields.length > 12 ? ', …' : '');
    lines.push(`| \`${name.replace(/\|/g, '\\|')}\` | ${info.rows} | ${fields.replace(/\|/g, '\\|')} |`);
  }
  lines.push('');
}

const out = join(repoRoot, 'docs/SOURCE-TABLES.md');
writeFileSync(out, lines.join('\n'));
console.log(`wrote ${out}: ${tables.size} tables`);

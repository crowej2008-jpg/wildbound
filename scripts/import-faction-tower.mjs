/**
 * M13.7: write packages/content/tuning/faction-tower.json (Faction Tower).
 *
 * From the source dumps:
 *   - the three towers and their 1,000-floor milestones: achievements_cfg (2026-10-03) lines 26 / 27 / 28
 *     ("Complete Water / Fire / Grass Tower", race_tower_type 21 / 22 / 23, 43 steps each, floors 10 … 1,000);
 *   - the Powerful Evolve boxes those steps pay: items_cfg item_hero_json 10251 / 10252 / 10253 (two 5★ cards each,
 *     equal weight);
 *   - the bought-sweep limit: vip_priv_json race_tower_num (2 at every VIP level).
 * From the owner's wiki (pokemon-wiki-sandy.vercel.app/game-modes/faction-tower, read 2026-11-04): the open days,
 * 20 floors a day, the Light / Dark allies, at least 4 of the type, two teams from floor 701, the 2 free sweeps and
 * 10 / 20 Diamond buys, and the per-floor pay (+500 Gold and +25 Star Shards every 5 floors, +10 Faction Coins
 * every 10, from 30,000 / 150 / 330 to 84,500 / 2,875 / 870). The every-5-floors one-time bonus is known at one
 * point only (floor 910: 10,650 coins, 29,750 Star Shards); it scales linearly from there (stand-in).
 * Item mapping: the 5S faction Pokémon Shards → generic 5-Star Pokémon Shards; Golden Egg Vouchers are left out
 * (the Golden Egg is not built, ASSUMPTIONS #84). The enemy curve is a stand-in (difficulty curves come last).
 *
 *   node scripts/import-faction-tower.mjs   (WILDBOUND_SOURCE as for the other importers)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { repoRoot, sourceRoot } from './source/source.mjs';

const load = (day, file) => JSON.parse(readFileSync(join(sourceRoot, day, file), 'utf8'));
const achievements = load('2026-10-03', 'achievements_cfg.json');
const items = load('2026-10-03', 'items_cfg.json');
const modes3 = load('2026-10-02', 'modes3_cfg.json');

const speciesBySource = new Map();
for (const file of ['water', 'fire', 'grass', 'light', 'dark', 'summon-pool']) {
  for (const s of JSON.parse(readFileSync(join(repoRoot, 'packages/content/species', `${file}.json`), 'utf8'))) {
    speciesBySource.set(s.sourceId, s);
  }
}

const TOWERS = { 21: 'water', 22: 'fire', 23: 'grass' };
const BOX = { water: 10251, fire: 10252, grass: 10253 };
const SHARD = { 10143: 'water', 10144: 'fire', 10145: 'grass' };
const GOLDEN_EGG = 10055;

const milestones = [];
for (const line of achievements._achievements.lines) {
  const m = /^\{race_tower_type,(\d+)\}$/.exec(line.target_counter ?? '');
  if (!m) continue;
  const faction = TOWERS[m[1]];
  if (!faction) throw new Error(`unknown tower type ${m[1]}`);
  for (const step of line.steps) {
    const row = { faction, floor: step.target_value, rewards: {}, evolveBox: 0 };
    for (const r of step.rewards) {
      if (r.item_id === BOX[faction]) row.evolveBox += r.qty;
      else if (SHARD[r.item_id] === faction) row.rewards.pokemonShard5 = (row.rewards.pokemonShard5 ?? 0) + r.qty;
      else if (r.item_id !== GOLDEN_EGG) throw new Error(`${faction} ${step.target_value}: unmapped reward ${r.item_id}`);
    }
    milestones.push(row);
  }
}
for (const f of Object.values(TOWERS)) {
  const n = milestones.filter((r) => r.faction === f);
  if (n.length !== 43 || n.at(-1).floor !== 1000) throw new Error(`${f}: ${n.length} milestones to ${n.at(-1)?.floor}`);
}

const heroBoxes = items.item_hero_json;
const evolveBoxes = {};
for (const [faction, item] of Object.entries(BOX)) {
  const row = heroBoxes[String(item)];
  if (!row || row.is_select !== 0) throw new Error(`no random item_hero row for ${item}`);
  evolveBoxes[faction] = row.hero_id_list.map(([kind, card, weight]) => {
    if (kind !== 2) throw new Error(`box ${item}: row kind ${kind}`);
    const s = speciesBySource.get(Math.floor(card / 10_000));
    if (!s) throw new Error(`box ${item}: no species for card ${card}`);
    const star = card % 100;
    if (!s.stars.some((c) => c.star === star)) throw new Error(`card ${card}: ${s.id} has no ${star}★`);
    return { species: s.id, star, weight };
  });
}

const buys = new Set(Object.values(modes3.vip_priv_json).map((v) => v.race_tower_num));
if (buys.size !== 1) throw new Error(`race_tower_num varies by VIP: ${[...buys]}`);
const open = modes3.sys_open_basic_json['64'];
if (open.name !== 'RACE_TOWER' || open.dungeon !== 102810) throw new Error('RACE_TOWER gate moved');

const tuning = {
  _note: 'Generated by scripts/import-faction-tower.mjs (source achievements / items / VIP tables + the owner\'s wiki). Do not edit.',
  floors: 1000,
  floorsPerDay: 20,
  twoTeamFrom: 701,
  minOfType: 4,
  allies: ['light', 'dark'],
  openDays: { water: [1, 4, 0], fire: [2, 5, 0], grass: [3, 6, 0] },
  freeSweeps: 2,
  sweepPrices: [10, 20].slice(0, [...buys][0]),
  pay: {
    gold: { base: 30000, step: 500, every: 5, max: 84500 },
    starShard: { base: 150, step: 25, every: 5, max: 2875 },
    factionCoin: { base: 330, step: 10, every: 10, max: 870 },
  },
  bonus: { every: 5, atFloor: 910, factionCoin: 10650, starShard: 29750 },
  milestones,
  evolveBoxes,
  enemy: { factions: [], tiers: [], count: 6, baseLevel: 31, levelSlope: 1.0014, starsEvery: 50, maxStars: 20, stageEvery: 250, maxStage: 3 },
};
writeFileSync(join(repoRoot, 'packages/content/tuning/faction-tower.json'), `${JSON.stringify(tuning, null, 2)}\n`);
console.log(`faction-tower.json: ${milestones.length} milestones, boxes ${Object.values(evolveBoxes).map((b) => b.map((r) => r.species).join('/')).join(', ')}`);

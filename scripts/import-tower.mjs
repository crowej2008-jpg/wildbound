#!/usr/bin/env node
/* eslint-disable no-undef */
/**
 * R9: import the source's Pokémon Tower into packages/content/tuning/tower.json.
 *
 * Source (modes2_cfg dun_tower_json): the Normal tower (difficulty 1, floors 1–1,000, stages of ten) and the Hard
 * tower (difficulty 2, floors 1–750, stages of five, each with a lineup rule). The table holds the achievement rows
 * only — the floors that pay a one-off reward (every 10 floors to 100, then every 5) and the Hard stages' rules;
 * the per-floor enemies and drops are not in the dumps.
 *
 *   node scripts/import-tower.mjs   (WILDBOUND_SOURCE as for the other importers)
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { loadTable, repoRoot } from './source/source.mjs';

const CURRENCY = {
  10103: 'pokemonShard5',
  10006: 'ticketPremium',
  10215: 'boxSupreme',
  10217: 'boxLegendary',
  10218: 'boxShinySupreme',
  10187: 'boxLD',
};
const SPECIES = { 40069: 'palkia', 40070: 'giratina', 40074: 'xerneas', 40081: 'shiny-gengar' };
const TITLE = { 80008: '12', 80009: '13', 80010: '14', 80011: '15' };

function reward(list) {
  const out = { rewards: {} };
  for (const [id, n] of list) {
    if (CURRENCY[id]) out.rewards[CURRENCY[id]] = (out.rewards[CURRENCY[id]] ?? 0) + n;
    else if (SPECIES[id]) out.speciesShards = { ...(out.speciesShards ?? {}), [SPECIES[id]]: n };
    else if (TITLE[id]) out.titleCard = TITLE[id];
    else throw new Error(`unknown tower reward ${id}`);
  }
  return out;
}

// "5号位无法上阵宠物" no Pokémon in position 5 · "1和5号位…" positions 1 and 5 · "最多上阵3个暗阵营宠物" at most 3 Dark ·
// "最多上阵2个攻宠" at most 2 attack (striker) · 防宠 defense (guardian) · 技宠 skill (adept) · 神话级 Mythic.
const FACTION = { 暗: 'dark', 草: 'grass', 火: 'fire', 光: 'light', 水: 'water' };
const CLASS = { 攻: 'striker', 防: 'guardian', 技: 'adept' };
function rule(desc) {
  let m = /^([\d和]+)号位无法上阵宠物$/.exec(desc);
  if (m) return { kind: 'noPositions', positions: m[1].split('和').map(Number) };
  m = /^最多上阵(\d)个(.)阵营宠物$/.exec(desc);
  if (m && FACTION[m[2]]) return { kind: 'maxFaction', max: Number(m[1]), faction: FACTION[m[2]] };
  m = /^最多上阵(\d)个(.)宠$/.exec(desc);
  if (m && CLASS[m[2]]) return { kind: 'maxClass', max: Number(m[1]), className: CLASS[m[2]] };
  m = /^最多上阵(\d)个神话级宠物$/.exec(desc);
  if (m) return { kind: 'maxTier', max: Number(m[1]), tier: 'mythic' };
  throw new Error(`unread tower rule "${desc}"`);
}

const rows = Object.entries(loadTable('dun_tower_json'))
  .filter(([k]) => !k.startsWith('_'))
  .map(([, r]) => r)
  .sort((a, b) => a.dun_id - b.dun_id);
const normal = rows
  .filter((r) => r.difficulty === 1)
  .map((r) => ({ floor: r.dun_id - 600000, ...reward(r.achieve_reward) }));
const hard = rows
  .filter((r) => r.difficulty === 2)
  .map((r) => ({ stage: r.dun_stage, floor: r.dun_id - 610000, rule: rule(r.desc), ...reward(r.achieve_reward) }));
if (normal.length !== 190 || hard.length !== 150) throw new Error(`${normal.length} / ${hard.length} rows`);
writeFileSync(
  join(repoRoot, 'packages/content/tuning/tower.json'),
  JSON.stringify(
    { _note: 'Generated by scripts/import-tower.mjs from the source (dun_tower_json). Do not edit.', normalFloors: 1000, hardFloors: 750, hardStageFloors: 5, normal, hard },
    null,
    1,
  ) + '\n',
);
console.log(`wrote ${normal.length} Normal and ${hard.length} Hard rows`);

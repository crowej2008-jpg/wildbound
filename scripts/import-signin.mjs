#!/usr/bin/env node
/* eslint-disable no-undef */
/**
 * R9: import the source's Sign In into packages/content/tuning/signin.json.
 *
 * Source (signin_cfg): sign_json — three identical 31-day calendars (calendar 1 runs once, 2 and 3 loop); each
 * day's reward and `double`, the VIP level from which that day pays double — and sign_heap_json, the signed-day
 * milestones (11 bonuses by day 31). vip_priv_json sign_patch_day / sign_patch_price: a missed day can be signed up
 * to 30 days later for 10 Diamonds at every VIP level.
 *
 *   WILDBOUND_SOURCE=…/h5-client node scripts/import-signin.mjs
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { loadTable, repoRoot } from './source/source.mjs';

// Source item → Wildbound currency.
const ITEM = {
  1: 'gold',
  2: 'gems',
  27: 'candy',
  10006: 'ticketPremium',
  10102: 'pokemonShard3',
  10103: 'pokemonShard5',
  20601: 'stone',
};
const rewards = (list) => {
  const out = {};
  for (const [item, n] of list) {
    const id = ITEM[item];
    if (!id) throw new Error(`unknown sign-in item ${item}`);
    out[id] = (out[id] ?? 0) + n;
  }
  return out;
};

const sign = loadTable('sign_json');
const heap = loadTable('sign_heap_json');
const cal = sign['1'];
const days = Object.keys(cal)
  .map(Number)
  .sort((a, b) => a - b)
  .map((day) => ({ day, rewards: rewards(cal[day].item_list), vipDouble: cal[day].double ?? null }));
const milestones = Object.keys(heap['1'])
  .map(Number)
  .sort((a, b) => a - b)
  .map((d) => ({ days: d, rewards: rewards(heap['1'][d].item_list) }));
// The three calendars are identical (kb); check so a re-extract that differs fails loudly.
for (const c of ['2', '3']) {
  if (JSON.stringify(Object.values(sign[c]).map((r) => r.item_list)) !== JSON.stringify(Object.values(cal).map((r) => r.item_list))) {
    throw new Error(`calendar ${c} differs from calendar 1`);
  }
}
const vip = Object.values(loadTable('vip_priv_json'));
const patchDays = vip[0].sign_patch_day;
const patchPrice = vip[0].sign_patch_price[0][1];
if (vip.some((v) => v.sign_patch_day !== patchDays || v.sign_patch_price[0][1] !== patchPrice)) {
  throw new Error('sign-in patch terms vary by VIP level');
}
if (days.length !== 31 || milestones.length !== 11) throw new Error(`${days.length} days / ${milestones.length} milestones`);
writeFileSync(
  join(repoRoot, 'packages/content/tuning/signin.json'),
  JSON.stringify(
    { _note: 'Generated by scripts/import-signin.mjs from the source (sign_json, sign_heap_json). Do not edit.', patchDays, patchGems: patchPrice, days, milestones },
    null,
    2,
  ) + '\n',
);
console.log(`wrote ${days.length} days, ${milestones.length} milestones, patch ${patchPrice} gems within ${patchDays} days`);

#!/usr/bin/env node
/* eslint-disable no-undef */
/**
 * R8: import the source's VIP into packages/content/tuning/vip.json.
 *
 * Source (vip_cfg): vip_priv_json — VIP 0–40, each with the Privilege XP it needs (charge_gold: the source counts
 * top-up Diamonds; Wildbound has no purchases, so the only Privilege XP is daily activity's — kb/vip-and-spending.md)
 * and its perks. Copied: the idle (AFK) XP Candy / Gold bonus, the idle cap, Quick Combat a day (and the free
 * ones), Arena attempt buys, daily dungeon buys, Daily Shop refreshes, the Pokémon bag, Golden Touch and the
 * one-time Exclusive Pack (source item ids, granted when the items exist in Wildbound — R9).
 *
 *   WILDBOUND_SOURCE=…/h5-client node scripts/import-vip.mjs
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { loadTable, repoRoot } from './source/source.mjs';

const rows = Object.values(loadTable('vip_priv_json')).sort((a, b) => a.lev - b.lev);
const pct = (pairs, id) => (pairs?.find(([k]) => k === id)?.[1] ?? 0) / 100;
const levels = rows.map((r) => ({
  level: r.lev,
  xp: r.charge_gold,
  showFrom: r.show_over_lev,
  idleCandyBonus: pct(r.guaji_reward_rate, 27),
  idleGoldBonus: pct(r.guaji_reward_rate, 1),
  idleCapHours: r.afk_max_hour,
  quickCombat: r.quick_max_num,
  quickCombatFree: r.quick_free_num,
  arenaBuys: r.arena_buy_num,
  dungeonBuys: r.daily_dun_buy_num,
  dailyShopRefreshes: r.shop_refresh_times?.find(([shop]) => shop === 1)?.[1] ?? 0,
  bag: r.bag_hero_num,
  goldenTouch: r.golden_hand,
  pack: (r.vipgift ?? []).map(([item, n]) => ({ item, n })),
}));
if (levels.length !== 41) throw new Error(`${levels.length} VIP rows`);
const out = {
  _note: 'Generated by scripts/import-vip.mjs from the source (vip_priv_json). Do not edit.',
  // kb: daily activity's 120-point chest pays Privilege XP ×60 every day.
  dailyActivityXp: 60,
  levels,
};
writeFileSync(join(repoRoot, 'packages/content/tuning/vip.json'), JSON.stringify(out, null, 1) + '\n');
console.log(`vip: ${levels.length} levels, VIP 40 at ${levels[40].xp} Privilege XP`);

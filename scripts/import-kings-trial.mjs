/**
 * M14.2: write packages/content/tuning/kings-trial.json (King's Trial) from the source's champion_challenge tables
 * (evening_cfg 2026-10-02): 7 regions, 36 Elite Four / Champion fights with their conditions (Victory Road gyms and
 * earlier trainers), Champion Point thresholds (`score`), progress chests (30 / 60 / 100), first-clear and champion
 * rewards and privileges; the 645 achievement tasks and 30 achievement rewards; the 16 weekly tasks.
 * The fights' enemies are not in the dumps (stand-in from the gyms they follow).
 *
 *   node scripts/import-kings-trial.mjs   (WILDBOUND_SOURCE as for the other importers)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { repoRoot, sourceRoot } from './source/source.mjs';

const e = JSON.parse(readFileSync(join(sourceRoot, '2026-10-02', 'evening_cfg.json'), 'utf8'));
const text = (s) => e._text?.[s] ?? s;
const itemName = (id) => e._items?.[String(id)] ?? String(id);
const TITLE_BY_CARD = new Map(JSON.parse(readFileSync(join(repoRoot, 'packages/content/titles/titles.json'), 'utf8')).map((t) => [t.card, t.id]));
const CURRENCY = { 2: 'gems', 1: 'gold', 10006: 'ticketPremium', 10103: 'pokemonShard5', 10262: 'pokemonShard4', 10059: 'resonationShard', 10012: 'berryEssence' };

function pay(list) {
  const rewards = {};
  const notCopied = [];
  let titleCard;
  for (const [id, n] of list ?? []) {
    if (id === 104) continue; // Champion Points are counted separately
    if (CURRENCY[id]) rewards[CURRENCY[id]] = (rewards[CURRENCY[id]] ?? 0) + n;
    else if (TITLE_BY_CARD.has(id)) titleCard = TITLE_BY_CARD.get(id);
    else notCopied.push(`${itemName(id)} ×${n}`);
  }
  return { rewards, ...(titleCard ? { titleCard } : {}), ...(notCopied.length ? { notCopied } : {}) };
}

const CLASS = ['striker', 'guardian', 'adept'];
const FACTION5 = ['grass', 'fire', 'water', 'light', 'dark'];
function perk(id, value) {
  if (id === undefined || id === null) return null;
  const v = value / 100;
  if (id >= 201 && id <= 203) return { field: 'hpPct', className: CLASS[id - 201], value: v };
  if (id >= 204 && id <= 208) return { field: 'hpPct', faction: FACTION5[id - 204], value: v };
  throw new Error(`unread King's Trial privilege ${id}`);
}

const areas = Object.values(e.champion_challenge_area_json)
  .sort((a, b) => a.area_id - b.area_id)
  .map((a) => ({ id: a.area_id, name: text(a.name) }));

const trainers = Object.values(e.champion_challenge_chapter_json)
  .sort((a, b) => a.chapter_id - b.chapter_id)
  .map((c) => {
    const gyms = c.conditions.filter((d) => d >= 3000100 && d < 3000200).map((d) => d - 3000100);
    const before = c.conditions.filter((d) => d >= 3000500 && d < 3000600).map((d) => d - 3000500);
    const chests = Object.values(e.champion_challenge_chapter_progress_json[String(c.chapter_id)] ?? {})
      .sort((a, b) => a.target_progress - b.target_progress)
      .map((p) => ({ progress: p.target_progress, ...pay(p.reward_items) }));
    return {
      index: c.chapter_id,
      area: c.area_id,
      name: text(c.chaptername),
      champion: c.boss_type === 2,
      points: c.score,
      gyms,
      trainers: before,
      chests,
      firstClear: pay([...(c.pass_reward ?? []), ...(c.boss_type === 2 ? c.show_reward ?? [] : [])]),
      perk: perk(c.privlege_id, c.privlege_value),
      perkText: c.privlege_id ? text(c.win_show_describe) : '',
    };
  });
if (trainers.length !== 36) throw new Error(`${trainers.length} trainers`);

const achTasks = Object.values(e.champion_challenge_ach_task_json)
  .sort((a, b) => a.index - b.index)
  .map((t) => ({ index: t.index, event: t.event, value: t.value, points: t.ach_value, desc: text(t.des) }));
const achRewards = Object.values(e.champion_challenge_ach_reward_json)
  .sort((a, b) => a.ach_value - b.ach_value)
  .map((r) => ({ index: r.index, points: r.ach_value, ...pay(r.reward) }));
const weekly = Object.values(e.champion_challenge_week_task_json)
  .sort((a, b) => a.id - b.id)
  .map((w) => ({ id: w.id, event: w.event, value: w.value, points: w.score, desc: text(w.desc), ...pay(w.reward) }));

writeFileSync(
  join(repoRoot, 'packages/content/tuning/kings-trial.json'),
  `${JSON.stringify({ _note: 'Generated by scripts/import-kings-trial.mjs from the source. Do not edit.', areas, trainers, achTasks, achRewards, weekly }, null, 1)}\n`,
);
const left = new Set([...trainers.flatMap((t) => [...(t.firstClear.notCopied ?? []), ...t.chests.flatMap((c) => c.notCopied ?? [])]), ...weekly.flatMap((w) => w.notCopied ?? [])]);
console.log(`kings-trial.json: ${trainers.length} trainers, ${achTasks.length} achievement tasks, ${weekly.length} weekly; not copied: ${[...left].join('; ')}`);

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { repoRoot, sourceRoot } from './source/source.mjs';

const modes = JSON.parse(readFileSync(join(sourceRoot, '2026-10-02', 'modes_cfg.json'), 'utf8'));
const modes2 = JSON.parse(readFileSync(join(sourceRoot, '2026-10-02', 'modes2_cfg.json'), 'utf8'));
const ITEM = {
  2: 'gems',
  10006: 'ticketPremium',
  10012: 'berryEssence',
  10017: 'reforgePotion',
  10805: 'awakeningStone',
  10806: 'squadCoin',
  29001: 'coreSkillStone',
  10803: 'jointTicket',
  110001: 'wildEnergyCan',
  110004: 'teleporter',
};
const names = { ...modes._items, ...modes2._items };
function pay(list) {
  const rewards = {};
  const notCopied = [];
  for (const [id, n] of list ?? []) {
    if (ITEM[id]) rewards[ITEM[id]] = (rewards[ITEM[id]] ?? 0) + n;
    else notCopied.push(`${(names[String(id)] ?? String(id)).trim()} ×${n}`);
  }
  return { rewards, ...(notCopied.length ? { notCopied } : {}) };
}
const rows = (o) => Object.values(o);

const jb = modes.cross_joint_team_pvp_basic_json;
const personal = rows(modes.cross_joint_team_pvp_personal_reward_json['10'] ?? rows(modes.cross_joint_team_pvp_personal_reward_json)[0])
  .sort((a, b) => a.battle_num - b.battle_num)
  .map((r) => ({ battles: r.battle_num, ...pay(r.reward) }));
const squad = rows(modes.cross_joint_team_pvp_team_reward_json['10'] ?? rows(modes.cross_joint_team_pvp_team_reward_json)[0])
  .sort((a, b) => a.score - b.score)
  .map((r) => ({ points: r.score, ...pay(r.reward) }));
const shop = rows(modes.cross_joint_team_shop_item_json)
  .sort((a, b) => a.index - b.index)
  .map((r) => ({ id: r.index, tier: r.page_id - 1, price: r.cost[0][1], limit: r.max_time, ...pay(r.item) }));

const gb = modes2.cross_giant_battle_basic_json;

#!/usr/bin/env node
/* eslint-disable no-undef */
/**
 * R8: import the source's six Trainer Tokens into packages/content/tuning/tokens.json.
 *
 * Source: celestica_trial_token_json (six tokens, one per Gods Trials season, five levels each: the season's
 * Suppression Treasure total each level needs — `balm_lv`, 0–60 — the token's own fragments it spends —
 * `lev_consume` — and its passive) and the token passives (skill_passivity 810201–811205, PvP-only stat lines read
 * from their text; the numbers match the 2026-10-01 screen reads, kb/account-boosts.md). English names from the
 * screen (Trainer ▸ Token).
 *
 *   WILDBOUND_SOURCE=…/h5-client node scripts/import-tokens.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { dumpFiles, loadTable, repoRoot } from './source/source.mjs';

const tokens = loadTable('celestica_trial_token_json');
const note = (key) =>
  dumpFiles()
    .map((f) => JSON.parse(readFileSync(f, 'utf8'))[key])
    .filter(Boolean)
    .pop();
const passives = note('_skill_passivity_token_skills');
if (!passives) throw new Error('no token passives in the dumps');

const NAMES = {
  101: ['Origin Emerald', 'Origin Emerald Fragments'],
  201: ['Sea Sound Bells', 'Sea Sound Bell Fragments'],
  301: ['Shadow Resonance Stone', 'Shadow Resonance Stone Shards'],
  401: ['Ultra Prism', 'Ultra Prism Fragments'],
  501: ['Immortal Sword', 'Immortal Sword Fragments'],
  601: ['Snow Leaf Badge', 'Snow Leaf Badge Fragments'],
};
// Longest terms first so 格挡强度 is not read as 格挡.
const TERMS = [
  ['PVP增伤', 'pvpBoost'],
  ['PVP减伤', 'pvpRdct'],
  ['格挡强度', 'blockPower'],
  ['格挡', 'block'],
  ['破防', 'guardBreak'],
  ['特攻增伤', 'sBoost'],
  ['特攻减伤', 'sRdct'],
  ['暴击强度', 'critPower'],
  ['暴击', 'crit'],
  ['暴抗', 'critRes'],
  ['物攻增伤', 'pBoost'],
  ['物攻减伤', 'pRdct'],
  ['控制增强', 'controlBoost'],
  ['控制抵抗', 'controlRes'],
];
function lines(desc) {
  const out = [];
  for (const m of desc.matchAll(/(\d+)%([^\d，,和]+)/g)) {
    const term = TERMS.find(([t]) => m[2].startsWith(t));
    if (!term) throw new Error(`unknown token term "${m[2]}" in "${desc}"`);
    out.push({ field: term[1], value: Number(m[1]) / 100 });
  }
  if (out.length === 0) throw new Error(`no lines in "${desc}"`);
  return out;
}

const out = Object.entries(tokens)
  .sort(([a], [b]) => Number(a) - Number(b))
  .map(([id, levels], season) => {
    const rows = Object.values(levels).sort((a, b) => a.lv - b.lv);
    const [name, fragmentName] = NAMES[id] ?? [];
    if (!name) throw new Error(`no name for token ${id}`);
    return {
      id: Number(id),
      name,
      season: season + 1,
      fragment: rows[0].lev_consume[0][0],
      fragmentName,
      levels: rows.map((r) => ({
        level: r.lv,
        treasureTotal: r.balm_lv,
        cost: r.lev_consume[0][1],
        lines: lines(passives[String(r.skill_id)].desc),
      })),
    };
  });
if (out.length !== 6 || out.some((t) => t.levels.length !== 5)) throw new Error('want 6 tokens × 5 levels');
const file = join(repoRoot, 'packages/content/tuning/tokens.json');
writeFileSync(
  file,
  JSON.stringify({ _note: 'Generated by scripts/import-tokens.mjs from the source (celestica_trial_token_json). Do not edit.', tokens: out }, null, 2) + '\n',
);
console.log(`wrote ${out.length} tokens`);

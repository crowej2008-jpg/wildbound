#!/usr/bin/env node
/* eslint-disable no-undef */
/**
 * R8: Mount, Back Decor, Follower and Outfits → packages/content/tuning/fashion.json.
 *
 * From the source (fashion_cfg): every piece (fashion_info_json: slot 1 outfit, 2 follower, 3 mount, 4 back decor;
 * names, the free starting pieces, "Event Rewards") and the 35 sets (fashion_suit_json: four pieces + a title,
 * bonuses at 2 / 3 / 5 pieces). The stone price per level is the client's: ceil(exp / 100) × 10.
 *
 * MADE UP (owner, 2026-11-01: "just make these numbers up" — the source's fashion_up_star_json and the per-skin
 * stats are not in the dumps). The shared level curve 0–200 and every piece's stats are invented, fitted to the
 * screen readings in kb/account-boosts.md: level 173 → 174 HP 146,481 → 148,148, Attack 21,701 → 21,948, 20.50%;
 * level 200 HP 195,000, Attack 28,890, 26%; level 173's bar 16,500; tiers of ten stars. Pieces use the three
 * bonus shapes read on screen (follower; mount / back decor; small pieces for outfits), 1★–15★.
 *
 *   WILDBOUND_SOURCE=…/h5-client node scripts/import-fashion.mjs
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { loadTable, loadTextMap, repoRoot } from './source/source.mjs';

const text = loadTextMap();
const SLOT = { 1: 'outfit', 2: 'follower', 3: 'mount', 4: 'backDecor' };

// --- Made-up level curve (quadratics through the three readings) -----------------------------------------------
const round = (v, to) => Math.round(v / to) * to;
const ladder = Array.from({ length: 201 }, (_, level) => {
  const tier = Math.min(20, Math.floor(level / 10) + 1);
  return {
    level,
    tier,
    star: level - (tier - 1) * 10,
    // Exp to the next level: 16,500 at 173 (seen), growing with the square of the level; none at the cap.
    exp: level === 200 ? 0 : Math.max(100, round(16_500 * (level / 173) ** 2, 100)),
    hp: Math.round(24.7 * level + 4.7515 * level ** 2),
    atk: Math.round(3.63 * level + 0.7041 * level ** 2),
    // Pokémon HP / Attack %, in 0.5% steps: 20.5% at 173–174, 26% at 200.
    pct: Math.round((26 * (level / 200) ** 1.645) * 2) / 200,
  };
});

// --- Made-up piece shapes (from the screen reads), per star 1–15 ------------------------------------------------
const SHAPE = {
  follower: { pct: 0.01, pctStep: 0.002, hp: 2945, hpStep: 589, atk: 465, atkStep: 93 },
  mount: { pct: 0.03, pctStep: 0.006, hp: 9845, hpStep: 1969, atk: 1555, atkStep: 311 },
  backDecor: { pct: 0.03, pctStep: 0.006, hp: 9845, hpStep: 1969, atk: 1555, atkStep: 311 },
  outfit: { pct: 0, pctStep: 0, hp: 1805, hpStep: 361, atk: 285, atkStep: 57 },
};

const info = loadTable('fashion_info_json');
const pieces = [];
for (const [slotId, rows] of Object.entries(info)) {
  const slot = SLOT[slotId];
  for (const r of Object.values(rows).sort((a, b) => a.sort - b.sort)) {
    const free = r.unlock_star === 0;
    pieces.push({
      slot,
      index: r.index,
      name: text[r.name] ?? r.name,
      free,
      // The free pieces show no bonus on screen (Arcanine).
      ...(free
        ? { shape: null }
        : { shape: { ...SHAPE[slot], pctStat: r.index % 2 === 1 ? 'hpPct' : 'atkPct' } }),
    });
  }
}

const ATTR = { 501: ['hp', 1], 502: ['pAtk', 1], 504: ['sAtk', 1], 406: ['hpPct', 10000], 407: ['pAtkPct', 10000], 409: ['sAtkPct', 10000] };
const suits = loadTable('fashion_suit_json');
const sets = Object.values(suits)
  .sort((a, b) => a['2'].suit_id - b['2'].suit_id)
  .map((byNum) => {
    const two = byNum['2'];
    return {
      id: two.suit_id,
      name: text[two.suit_name] ?? two.suit_name,
      pieces: two.suit_condition.map(([slot, index]) => ({ slot: SLOT[slot], index })),
      title: String(two.suit_title),
      bonuses: ['2', '3', '5'].map((n) => ({
        pieces: Number(n),
        lines: byNum[n].attrs.map(([id, v]) => {
          const a = ATTR[id];
          if (!a) throw new Error(`unknown set attr ${id}`);
          return { field: a[0], value: v / a[1] };
        }),
      })),
    };
  });
if (sets.length !== 35) throw new Error(`${sets.length} sets`);

writeFileSync(
  join(repoRoot, 'packages/content/tuning/fashion.json'),
  JSON.stringify(
    {
      _note:
        'Generated by scripts/import-fashion.mjs. Pieces and sets are the source; the level curve and piece stats are made up (owner, 2026-11-01).',
      maxStar: 15,
      ladder,
      pieces,
      sets,
    },
    null,
    1,
  ) + '\n',
);
const total = ladder.reduce((s, r) => s + r.exp, 0);
console.log(`wrote ${pieces.length} pieces, ${sets.length} sets; 0 → 200 = ${total.toLocaleString()} exp`, ladder[173], ladder[174], ladder[200]);

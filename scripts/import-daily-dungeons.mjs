#!/usr/bin/env node
/* eslint-disable no-undef */
/**
 * R9: import the source's four daily dungeons into packages/content/tuning/daily-dungeons.json.
 *
 * Source (modepages-pve): dun_daily_dun_json (Gold 4, Vanity 5, XP & ASC 8, Shard 9; open every day), dun_basic_json
 * (ten difficulties each: the trainer level that opens it, 2 runs a day, 10-round fights, the sweep reward = the S
 * pay), dun_score_config_json (difficulty names) and dun_score_reward_json (per grade: the goal — kills or damage,
 * within N rounds — what a fight at that grade pays, and the one-off grade chest). The enemies (monster_bag_id) are
 * not in the dumps; Wildbound's enemy curve stands in.
 *
 *   node scripts/import-daily-dungeons.mjs   (reads the dump file directly)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { dumpFiles, repoRoot } from './source/source.mjs';

const file = dumpFiles().find((f) => f.endsWith('modepages-pve_cfg.json'));
const dump = JSON.parse(readFileSync(file, 'utf8'));
const basic = dump[Object.keys(dump).find((k) => k.startsWith('dun_basic_json'))];
const names = dump.dun_score_config_json;
const grades = dump.dun_score_reward_json;

const ITEM = {
  1: 'gold',
  27: 'candy',
  20601: 'stone',
  21102: 'followerStone',
  21103: 'mountStone',
  21104: 'backDecorStone',
  10109: 'cosmeticBox',
  10102: 'pokemonShard3',
  10262: 'pokemonShard4',
  10103: 'pokemonShard5',
};
const rewards = (list) => {
  const out = {};
  for (const [id, n] of list ?? []) {
    if (!ITEM[id]) throw new Error(`unknown dungeon item ${id}`);
    out[ITEM[id]] = n;
  }
  return out;
};
const DIFF = {
  入门: 'Entry',
  简单: 'Easy',
  普通: 'Normal',
  困难: 'Hard',
  噩梦1: 'Nightmare 1',
  噩梦2: 'Nightmare 2',
  地狱1: 'Hell 1',
  地狱2: 'Hell 2',
  修罗1: 'Shura 1',
  修罗2: 'Shura 2',
};
const DUNGEON = {
  4: ['gold', 'Gold', 'Defeat as many Pokémon as you can within the rounds to earn more Gold.'],
  5: ['vanity', 'Vanity', 'Deal as much damage as you can within the rounds to earn more Mount, Back Decor and Follower stones.'],
  8: ['xp', 'XP & ASC', 'Defeat the high-defense Squirtle for more XP Candies and Ascension Stones.'],
  9: ['shard', 'Shard', 'Defeat Mewtwo for Pokémon Shards — watch out for its attacks!'],
};
// "击杀3宠" kill 3 · "7回合内击杀6宠" kill 6 within 7 rounds · "造成13w伤害" deal 130,000 · "4回合内造成15w伤害".
function goal(desc) {
  const rounds = /(\d+)回合内/.exec(desc)?.[1];
  const kills = /击杀(\d+)宠/.exec(desc)?.[1];
  const dmg = /造成([\d.]+)w伤害/.exec(desc)?.[1];
  if (!kills && !dmg) throw new Error(`unread grade goal "${desc}"`);
  return {
    ...(kills ? { kills: Number(kills) } : { damage: Math.round(Number(dmg) * 10_000) }),
    ...(rounds ? { rounds: Number(rounds) } : {}),
  };
}

const dungeons = Object.values(dump.dun_daily_dun_json)
  .sort((a, b) => a.sort - b.sort)
  .map((d) => {
    const [id, name, desc] = DUNGEON[d.dun_type];
    const rows = Object.values(basic)
      .filter((r) => r.dun_type === d.dun_type)
      .sort((a, b) => a.role_lev - b.role_lev);
    return {
      id,
      name,
      desc,
      runs: rows[0].Times,
      rounds: rows[0].battle_turn,
      difficulties: rows.map((r) => {
        const g = grades[String(r.dun_id)];
        return {
          id: String(r.dun_id),
          name: DIFF[names[String(r.dun_id)].hard_desc] ?? names[String(r.dun_id)].hard_desc,
          level: r.role_lev,
          sweep: rewards(r.sweep_reward),
          winPay: rewards(g['0'].battle_reward),
          grades: ['1', '2', '3', '4'].map((k, i) => ({
            grade: ['C', 'B', 'A', 'S'][i],
            ...goal(g[k].score_desc),
            pay: rewards(g[k].battle_reward),
            chest: rewards(g[k].score_reward),
          })),
        };
      }),
    };
  });
if (dungeons.length !== 4 || dungeons.some((d) => d.difficulties.length !== 10)) throw new Error('want 4 × 10');
writeFileSync(
  join(repoRoot, 'packages/content/tuning/daily-dungeons.json'),
  JSON.stringify({ _note: 'Generated by scripts/import-daily-dungeons.mjs from the source. Do not edit.', dungeons }, null, 1) + '\n',
);
console.log('wrote', dungeons.map((d) => `${d.name} ${d.difficulties.map((x) => x.level).join('/')}`).join(' · '));
